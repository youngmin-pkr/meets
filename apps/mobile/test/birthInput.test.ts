import { describeIsoDate, parseBirthInput } from '../src/birthInput';

describe('생년월일 입력 읽기', () => {
  test.each([
    ['000501', '2000-05-01'],
    ['20000501', '2000-05-01'],
    ['2000-05-01', '2000-05-01'],
    ['2000.05.01', '2000-05-01'],
    ['2000 05 01', '2000-05-01'],
    ['950312', '1995-03-12'],
    ['150101', '2015-01-01'],
    ['260101', '2026-01-01'], // 올해(2026)까지는 2000년대
    ['270101', '1927-01-01'], // 올해보다 미래면 1900년대
  ])('%s → %s', (text, iso) => {
    expect(parseBirthInput(text, 2026)).toBe(iso);
  });

  test.each(['', '0005', '2000051', '000230', '20001301', '2000-5-1', 'abcdef', '000501!'])(
    '읽을 수 없는 값(%s)은 null',
    (text) => {
      expect(parseBirthInput(text, 2026)).toBeNull();
    },
  );

  test('보기 좋은 글로 바꾼다', () => {
    expect(describeIsoDate('2000-05-01')).toBe('2000년 5월 1일');
  });
});
